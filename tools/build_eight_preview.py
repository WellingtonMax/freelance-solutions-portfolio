def git(root: Path, *args: str) -> bytes:
    return subprocess.check_output(["git", "-C", str(root), *args], stderr=subprocess.PIPE)


def fetch_heads(root: Path) -> None:
    for pr in dict.fromkeys(item[2] for item in PROJECTS):
        dest = f"refs/remotes/origin/preview-pr-{pr}"
        subprocess.run(["git", "-C", str(root), "fetch", "--no-tags", "origin",
                        f"+refs/pull/{pr}/head:{dest}"], check=True)


def assemble(root: Path, output: Path, *, reader=None, generate_quote=None) -> dict[int, str]:
    # Refuse output collisions, including symlinks: never overwrite prior work.
    output.mkdir(parents=True, exist_ok=False)
    read = reader or (lambda ref, path: git(root, "show", f"{ref}:{path}"))
    commits = {}
    for _, _, pr, _, paths in PROJECTS:
        ref = f"refs/remotes/origin/preview-pr-{pr}"
        if pr not in commits:
            commits[pr] = git(root, "rev-parse", ref).decode("ascii").strip() if reader is None else f"fixture-pr-{pr}"
        for relative in paths:
            # Every relative path is a constant from the manifest, not arbitrary input.
            dest = output / relative
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(read(ref, relative))
    (output / "SECURITY.md").write_bytes(read("HEAD", "SECURITY.md"))
    factory = output / "06-document-factory"
    quote = factory / "quotation.html"
    if generate_quote is None:
        subprocess.run([sys.executable, "factory.py", "sample.json", "quotation.html"],
                       cwd=factory, check=True, timeout=20)
    else:
        generate_quote(factory)
    if not quote.is_file() or not quote.read_text(encoding="utf-8").lstrip().lower().startswith("<!doctype html>"):
        raise ValueError("Document Factory did not generate an HTML quotation")
    (output / "index.html").write_text(render_index(commits), encoding="utf-8")
    for _, _, _, entry, _ in PROJECTS:
        assert (output / entry).is_file(), f"Missing preview {entry}"
    return commits


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fetch", action="store_true", help="Fetch public GitHub PR heads (read-only remote operation)")
    parser.add_argument("--output", type=Path, default=Path("preview-eight"), help="New output directory; must not already exist")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if args.fetch:
        fetch_heads(root)
    output = args.output.absolute()
    if os.path.lexists(output):
        parser.error(f"Refusing to overwrite {output}")
    try:
        commits = assemble(root, output)
    except (subprocess.CalledProcessError, FileNotFoundError, ValueError) as exc:
        parser.exit(1, f"Preview incomplete in {output}; inspect before manually removing it. Error: {exc}\n")
    print(f"Created {output / 'index.html'} from {len(commits)} PR heads; no deployment performed.")


if __name__ == "__main__":
    main()
